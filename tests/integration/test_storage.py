async def test_tracks_and_alerts_do_not_collide_in_one_redis(clean_redis: str) -> None:
    """Both stores share a database; their key prefixes must not overlap."""
    tracks = LiveTrackStore.from_url(clean_redis)
    alerts = LiveAlertStore.from_url(clean_redis)
    try:
        await tracks.publish([a_track_update()])
        await alerts.apply([an_alert()])
        assert len(await tracks.live()) == 1
        assert len(await alerts.active()) == 1
    finally:
        await tracks.close()
        await alerts.close()
