async def test_the_live_picture_holds_the_newest_update_per_track(clean_redis: str) -> None:
    store = LiveTrackStore.from_url(clean_redis)
    try:
        moments = seconds_apart(5)
        for index, moment in enumerate(moments):
            await store.publish([a_track_update(at=moment, lon=-75.0 + index)])

        live = await store.live()
        assert len(live) == 1
        assert live[0].lon == pytest.approx(-75.0 + 4)
    finally:
        await store.close()


async def test_a_stale_track_falls_outside_the_window(clean_redis: str) -> None:
    store = LiveTrackStore.from_url(clean_redis)
    try:
        old = datetime.now(UTC) - timedelta(minutes=5)
        await store.publish([a_track_update(at=old)])
        assert await store.live(since=datetime.now(UTC) - timedelta(seconds=20)) == []
        assert len(await store.live()) == 1
    finally:
        await store.close()


async def test_a_forgotten_track_disappears_immediately(clean_redis: str) -> None:
    """A terminated aircraft must leave the display rather than wait for a TTL."""
    store = LiveTrackStore.from_url(clean_redis)
    try:
        await store.publish([a_track_update()])
        await store.forget(["trk-a1b2c3"])
        assert await store.live() == []
    finally:
        await store.close()


async def test_the_live_entry_expires_on_its_own(clean_redis: str) -> None:
    """If the tracker dies the picture must empty itself.

    A frozen display is more dangerous than an empty one, so expiry is a safety
    property rather than a caching detail.
    """
    store = LiveTrackStore.from_url(clean_redis, ttl_s=1)
    try:
        await store.publish([a_track_update()])
        assert len(await store.live()) == 1

        async def gone() -> bool:
            return not await store.live()

        await until(gone, timeout_s=15.0, description="the live entry to expire")
    finally:
        await store.close()


async def test_active_alerts_round_trip(clean_redis: str) -> None:
    store = LiveAlertStore.from_url(clean_redis)
    try:
        await store.apply([an_alert()])
        active = await store.active()
        assert len(active) == 1
        assert active[0].conflict is not None
        assert active[0].conflict.min_horizontal_sep_nm == 2.0
    finally:
        await store.close()


async def test_a_cleared_alert_is_deleted_rather_than_flagged(clean_redis: str) -> None:
    """The endpoint's contract is "what is wrong now".

    Keeping cleared alerts with a flag would mean every consumer had to remember
    to filter them, and the first one that forgot would show a resolved conflict
    as live.
    """
    store = LiveAlertStore.from_url(clean_redis)
    try:
        await store.apply([an_alert()])
        await store.apply([an_alert(state=AlertState.CLEARED)])
        assert await store.active() == []
    finally:
        await store.close()


async def test_a_sustained_alert_replaces_the_previous_state(clean_redis: str) -> None:
    store = LiveAlertStore.from_url(clean_redis)
    try:
        await store.apply([an_alert(summary="first")])
        await store.apply([an_alert(state=AlertState.SUSTAINED, summary="second")])
        active = await store.active()
        assert len(active) == 1
        assert active[0].summary == "second"
        assert active[0].state is AlertState.SUSTAINED
    finally:
        await store.close()


async def test_alerts_expire_if_nothing_maintains_them(clean_redis: str) -> None:
    """If the conformance service dies, its alerts must not sit on the display
    forever with nothing keeping them current."""
    store = LiveAlertStore.from_url(clean_redis, ttl_s=1)
    try:
        await store.apply([an_alert()])
        assert len(await store.active()) == 1

        async def gone() -> bool:
            return not await store.active()

        await until(gone, timeout_s=15.0, description="the alert to expire")
    finally:
        await store.close()


