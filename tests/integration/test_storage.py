async def test_the_migration_produces_the_tables_the_writer_expects(
    migrated_postgres: str,
) -> None:
    engine = create_async_engine(migrated_postgres)
    try:
        async with engine.connect() as conn:
            tables = {
                row[0]
                for row in (
                    await conn.execute(
                        text("select tablename from pg_tables where schemaname='public'")
                    )
                ).all()
            }
            constraints = {
                row[0]
                for row in (
                    await conn.execute(
                        text(
                            "select conname from pg_constraint"
                            " where conrelid='track_points'::regclass"
                        )
                    )
                ).all()
            }
    finally:
        await engine.dispose()

    assert {"tracks", "track_points"} <= tables
    # Referenced by name in the writer's ON CONFLICT clause. An autogenerated
    # rename would break idempotency silently, so the name is pinned.
    assert "uq_track_points_track_observed" in constraints


async def test_track_history_is_written_and_read_back(migrated_postgres: str) -> None:
    store = TrackHistoryStore.from_dsn(migrated_postgres)
    try:
        moments = seconds_apart(5, start=datetime(2026, 3, 1, tzinfo=UTC))
        await store.record([a_track_update(track_id="trk-read", at=m) for m in moments])

        history = await store.history("trk-read")
        assert len(history) == 5
        # Oldest first: a display drawing a trail needs them in flight order.
        assert [row["observed_at"] for row in history] == moments
    finally:
        await store.dispose()


async def test_replaying_the_same_batch_does_not_duplicate_history(
    migrated_postgres: str,
) -> None:
    """The idempotency claim, demonstrated against the real constraint.

    Without it, every consumer restart would silently inflate track history in a
    way that is very hard to notice afterwards.
    """
    store = TrackHistoryStore.from_dsn(migrated_postgres)
    try:
        moments = seconds_apart(20, start=datetime(2026, 3, 2, tzinfo=UTC))
        batch = [a_track_update(track_id="trk-replay", at=m) for m in moments]

        await store.record(batch)
        await store.record(batch)
        await store.record(batch)

        assert len(await store.history("trk-replay")) == 20
    finally:
        await store.dispose()


async def test_a_batch_holding_many_updates_for_one_track_is_accepted(
    migrated_postgres: str,
) -> None:
    """Postgres refuses an ON CONFLICT DO UPDATE that touches a row twice.

    A batch normally holds several updates per aircraft, so the writer collapses
    to the newest per track. This is the regression test for the crash that
    found it.
    """
    store = TrackHistoryStore.from_dsn(migrated_postgres)
    try:
        moments = seconds_apart(50, start=datetime(2026, 3, 3, tzinfo=UTC))
        await store.record([a_track_update(track_id="trk-batch", at=m) for m in moments])
        assert len(await store.history("trk-batch")) == 50
    finally:
        await store.dispose()


async def test_the_track_row_reflects_the_newest_update(migrated_postgres: str) -> None:
    store = TrackHistoryStore.from_dsn(migrated_postgres)
    engine = create_async_engine(migrated_postgres)
    try:
        moments = seconds_apart(10, start=datetime(2026, 3, 4, tzinfo=UTC))
        await store.record([a_track_update(track_id="trk-latest", at=m) for m in moments])

        async with engine.connect() as conn:
            row = (
                await conn.execute(
                    text(
                        "select first_seen_at, last_seen_at from tracks where track_id='trk-latest'"
                    )
                )
            ).one()
        # first_seen_at must stay at the first, not follow the last.
        assert row[0] == moments[0]
        assert row[1] == moments[-1]
    finally:
        await store.dispose()
        await engine.dispose()


