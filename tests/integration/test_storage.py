"""The storage layer, against real Postgres and Redis.

The claim that matters here is **idempotency under redelivery**. At-least-once
delivery means a replayed report will arrive; the unique constraint plus
`ON CONFLICT DO NOTHING` is what stops that inflating history. A mock cannot
demonstrate that, because the constraint lives in the database.

The schema is applied by Alembic, not by `metadata.create_all`, so these tests
run against the schema that actually ships.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from acp.common.contracts import Alert as AlertModel
from acp.common.contracts import (
    AlertKind,
    AlertState,
    ConflictEvidence,
    DataSource,
    Severity,
)
from acp.storage.stores import LiveAlertStore, LiveTrackStore, TrackHistoryStore
from tests.integration.helpers import a_track_update, seconds_apart, until

pytestmark = pytest.mark.integration


def an_alert(key: str = "predicted_conflict:trk-a:trk-b", **overrides: object) -> AlertModel:
    now = datetime.now(UTC)
    fields: dict[str, object] = {
        "alert_id": "al-1",
        "alert_key": key,
        "kind": AlertKind.PREDICTED_CONFLICT,
        "severity": Severity.CAUTION,
        "state": AlertState.NEW,
        "raised_at": now,
        "updated_at": now,
        "track_ids": ("trk-a", "trk-b"),
        "reason_codes": ("horizontal_below_standard",),
        "summary": "integration alert",
        "conflict": ConflictEvidence(
            time_to_cpa_s=120.0,
            min_horizontal_sep_nm=2.0,
            min_vertical_sep_ft=400.0,
            lookahead_s=300.0,
            horizontal_standard_nm=5.0,
            vertical_standard_ft=1000.0,
        ),
        "source": DataSource.SIMULATOR,
    }
    fields.update(overrides)
    return AlertModel(**fields)  # type: ignore[arg-type]


